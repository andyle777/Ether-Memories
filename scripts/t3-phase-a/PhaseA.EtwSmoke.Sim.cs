// Offline simulator only. No ETW/session/native collector implementation exists here.
using System;
using System.ComponentModel;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Threading;

namespace Orion.EtwSmoke {
  public sealed class Plan {
    public bool OwnerMismatch, SettingsMismatch, CollectorFailure, StopFailure;
    public bool EventLoss, BufferLoss, MissingCompletion, Replay, Contradictory, Cancellation;
    public int DelayMs;
    public int AcceptedBufferKB=64, AcceptedMinBuffers=64, AcceptedMaxBuffers=128, AcceptedMaxFileMB=128;
    public int EventsLost=0, BuffersLost=0;
    public int FinalEventsLost=0, FinalBuffersLost=0;
    public bool OwnershipChangesBeforeStop;
  }
  public sealed class Result {
    public string Status="UNVERIFIED", Reason="NOT_STARTED", Cleanup="NOT_STARTED", CleanupReason="NOT_RUN", DirectoryPath="";
    public int StopAttempts;
    public int EventsLost=-1, BuffersLost=-1;
    public int FinalEventsLost=-1, FinalBuffersLost=-1;
    public bool EvidenceRetained, ResourceUnresolved;
  }
  // The concrete simulator is deliberately not a trusted collector interface.
  // Scenario fields supply mock responses only and cannot produce LIVE evidence.
  internal sealed class SimulatedCollector {
    internal readonly Plan P;
    internal readonly string SessionId;
    internal SimulatedCollector(Plan p,string id){P=p;SessionId=id;}
    internal bool Owns(string expected){return !P.OwnerMismatch && SessionId==expected;}
    internal bool SettingsAccepted(){return !P.SettingsMismatch && P.AcceptedBufferKB==64 && P.AcceptedMinBuffers==64 && P.AcceptedMaxBuffers==128 && P.AcceptedMaxFileMB==128;}
    internal bool Stop(string expected){return Owns(expected) && !P.StopFailure;}
  }
  public static class Simulation {
    [DllImport("kernel32.dll",CharSet=CharSet.Unicode,SetLastError=true)]
    private static extern bool CreateDirectoryW(string path,IntPtr security);
    public static Result Run(string parent,string id,Plan plan,int timeoutMs) {
      var r=new Result(); var clock=Stopwatch.StartNew();
      if(plan==null || timeoutMs<1 || timeoutMs>30000 || String.IsNullOrEmpty(id) || id.Length!=32 || !IsHex(id)) {r.Reason="INVALID_INPUT";return r;}
      try {
        var root=Path.GetFullPath(parent);
        if(!Directory.Exists(root) || (File.GetAttributes(root)&FileAttributes.ReparsePoint)!=0){r.Reason="INVALID_PARENT";return r;}
        r.DirectoryPath=Path.Combine(root,"orion-etw-"+id);
        if(!CreateDirectoryW(r.DirectoryPath,IntPtr.Zero)) {
          int error=Marshal.GetLastWin32Error();r.Reason=error==183?"DIRECTORY_COLLISION":"DIRECTORY_CREATE_FAILED";return r;
        }
      } catch(Exception) {r.Reason="DIRECTORY_CREATE_FAILED";return r;}
      // The synthetic session identity is generated by the controller, not an input label.
      string session=Guid.NewGuid().ToString("N");var collector=new SimulatedCollector(plan,session);
      r.EvidenceRetained=true;
      if(plan.DelayMs<0){r.Reason="INVALID_INPUT";return r;}
      int remaining=timeoutMs-(int)clock.ElapsedMilliseconds;
      if(remaining<=0 || plan.DelayMs>=remaining) {
        if(remaining>0) Thread.Sleep(remaining);
        r.Reason="TIMEOUT";r.Cleanup="UNCONFIRMED";r.ResourceUnresolved=true;return r;
      }
      if(plan.DelayMs>0)Thread.Sleep(plan.DelayMs);
      if(clock.ElapsedMilliseconds>=timeoutMs){r.Reason="TIMEOUT";r.Cleanup="UNCONFIRMED";r.ResourceUnresolved=true;return r;}
      if(!collector.Owns(session)){r.Reason="OWNERSHIP_UNCONFIRMED";r.Cleanup="UNCONFIRMED";r.ResourceUnresolved=true;return r;}
      r.EventsLost=plan.EventsLost;r.BuffersLost=plan.BuffersLost;
      string reason=plan.Cancellation?"CANCELLED":!collector.SettingsAccepted()?"SETTINGS_MISMATCH":plan.CollectorFailure?"COLLECTOR_FAILED":(plan.EventsLost<0 || plan.BuffersLost<0)?"LOSS_COUNTERS_MISSING":(plan.EventLoss || plan.EventsLost>0)?"EVENT_LOSS":(plan.BufferLoss || plan.BuffersLost>0)?"BUFFER_LOSS":plan.MissingCompletion?"COMPLETION_MISSING":plan.Replay?"REPLAY_DETECTED":plan.Contradictory?"CONTRADICTORY_RECORDS":"SIMULATED_COMPLETE";
      // Recheck simulated ownership immediately before the simulated stop.
      if(plan.OwnershipChangesBeforeStop || !collector.Owns(session)){r.Reason=reason=="SIMULATED_COMPLETE"?"OWNERSHIP_UNCONFIRMED":reason;r.Cleanup="UNCONFIRMED";r.CleanupReason="OWNERSHIP_UNCONFIRMED";r.ResourceUnresolved=true;return r;}
      if(clock.ElapsedMilliseconds>=timeoutMs){r.Reason="TIMEOUT";r.Cleanup="UNCONFIRMED";r.ResourceUnresolved=true;return r;}
      r.StopAttempts++;
      if(!collector.Stop(session)){r.Reason=reason=="SIMULATED_COMPLETE"?"STOP_FAILED":reason;r.Cleanup="UNCONFIRMED";r.CleanupReason="STOP_FAILED";r.ResourceUnresolved=true;return r;}
      r.Cleanup="CONFIRMED_SIMULATED";r.CleanupReason="NONE";
      r.FinalEventsLost=plan.FinalEventsLost;r.FinalBuffersLost=plan.FinalBuffersLost;
      if(reason=="SIMULATED_COMPLETE") reason=(r.FinalEventsLost<0 || r.FinalBuffersLost<0)?"LOSS_COUNTERS_MISSING":r.FinalEventsLost>0?"EVENT_LOSS":r.FinalBuffersLost>0?"BUFFER_LOSS":reason;
      r.Reason=reason;return r;
    }
    private static bool IsHex(string s){foreach(char c in s)if(!((c>='0'&&c<='9')||(c>='a'&&c<='f')))return false;return true;}
  }
}
